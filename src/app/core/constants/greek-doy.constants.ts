/**
 * Resolves a numeric DOY code (e.g., '4290') to its official Greek description ('ΚΙΛΚΙΣ').
 * If a Greek textual string is already supplied, it returns it cleaned.
 */
export function resolveGreekDoy(doyOrCode: string | null | undefined): string {
  if (!doyOrCode) return '';
  const trimmed = String(doyOrCode).trim();
  
  // Return early if empty or already recognized
  if (!trimmed) return '';

  // 1. Exact match by numeric code
  if (GREEK_DOY_MAP[trimmed]) {
    return GREEK_DOY_MAP[trimmed];
  }

  // 2. If already Greek text (contains Greek unicode characters), return as-is
  if (/[\u0370-\u03FF]/.test(trimmed)) {
    return trimmed;
  }

  // Fallback: return the input string if unknown
  return trimmed;
}